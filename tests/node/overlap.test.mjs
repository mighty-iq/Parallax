/* Test-overlap notes and the two settings behind PAT focus and "Taking a test soon?"
   (js/ui/overlap.js; v1.1 PLAN M5, M6; R4 §6). overlap.js is a UI file without DOM work at load,
   so it runs here with the store and stub exercises: the notes, the helper's matching, the pause
   and its end, PAT-focus history, noted tests, and that all of it survives a save and a reload. */
import { MANIFEST, SharedStorage } from './run.mjs';

const T0 = Date.UTC(2026, 10, 13, 10, 0, 0);
const OVERLAP = 'js/ui/overlap.js';
const ADA = 'DAT® and Dental Admission Test are marks of the American Dental Association. Parallax is not affiliated with or endorsed by the ADA. Every item is generated by the app; none is taken from the DAT.';
const IDS = ['fold', 'hidden', 'views', 'nets', 'span', 'rotate', 'spin', 'slice', 'orient', 'homing', 'patviews', 'angles', 'patfold', 'cubes'];
const PAT = ['openings', 'patviews', 'angles', 'patfold', 'cubes', 'form'];
const clone = (x) => JSON.parse(JSON.stringify(x));

function define(PX, ids = IDS) {
  ids.forEach((id, i) => {
    PX.ex.define({
      id, code: (PAT.includes(id) ? 'PAT-' : 'EX-') + (i + 1), name: id, short: id.charAt(0).toUpperCase() + id.slice(1),
      abilities: ['Vz'], cell: null, role: 'train', pat: PAT.includes(id), answer: 'choice', nOptions: 4, base: -2,
      dims: [{ key: 'a', label: 'A', levels: [0, 1], step: 0.5 }],
      chance() { return 0.25; },
      generate(rng, params) { return { ex: id, seed: rng.seed, params, key: 0 }; },
      validate() { return true; },
      score(item, r) { return { correct: r === item.key }; },
    });
  });
}

function env(t, storage, ids) {
  const e = t.env({ files: [...MANIFEST, OVERLAP], exercises: false, storage: storage || new SharedStorage(), now: T0 });
  t.ok(!e.loadErrors.length, 'overlap.js loads: ' + e.loadErrors.join(' | '));
  define(e.PX, ids);
  return e;
}

export async function run(t) {
  testNotes(t);
  testMatch(t);
  testSettings(t);
  testPersist(t);
  testWording(t);
}

function testNotes(t) {
  t.section('overlap notes');
  const { PX } = env(t);
  const O = PX.ui.overlap;
  t.eq(O.ADA, ADA, 'the ADA line, word for word (PLAN M5)');
  for (const id of ['fold', 'hidden', 'views', 'nets', 'span']) {
    const n = O.noteFor(id);
    t.ok(n && n.label === 'Also in tests' && n.text.length > 60 && n.legal === null, id + ' has an "Also in tests" note without the ADA line');
    t.ok(/say that you have practised\.$/.test(n.text), id + ': the note ends with what to do');
  }
  t.ok(/count format/.test(O.noteFor('views').text) && /every cube is visible/.test(O.noteFor('views').text), 'Views: the count format, and the difference from tests');
  for (const id of PAT) {
    const n = O.noteFor(id);
    t.ok(n && /Perceptual Ability Test/.test(n.text) && n.legal === ADA, id + ': a DAT-style note names the test and carries the ADA line');
    t.ok(/has not measured its effect on DAT scores/.test(n.text), id + ': no score claim');
  }
  for (const id of ['rotate', 'spin', 'slice', 'orient', 'homing', 'track', 'nope']) t.eq(O.noteFor(id), null, id + ': no note');
  t.eq(O.noteNode('fold'), null, 'noteNode needs the DOM helper (none in Node)');
  t.eq(O.patIds(), ['patviews', 'angles', 'patfold', 'cubes'], 'patIds: the DAT-style exercises this build has, PAT order');
}

function testMatch(t) {
  t.section('overlap helper matching');
  const { PX } = env(t);
  const O = PX.ui.overlap;
  t.eq(O.KINDS.map((k) => k.id), ['folding', 'hidden', 'counting', 'nets', 'views', 'openings', 'angles', 'sections', 'rotation', 'directions', 'tapping', 'analogies', 'matrices', 'dat', 'unsure'], 'the kinds a test can contain');
  t.ok(O.KINDS.every((k) => k.same.concat(k.related).every((id) => /^[a-z][a-z0-9-]*$/.test(id))), 'every kind lists exercise ids');
  let m = O.match(['folding']);
  t.eq([m.same, m.related, m.untrained], [['fold', 'patfold'], [], []], 'paper folding: Fold and Hole Punch');
  m = O.match(['nets']);
  t.eq([m.same, m.related], [['nets'], ['fold']], 'nets: Form is missing here, so only Nets; Fold related');
  m = O.match(['nets', 'folding']);
  t.eq([m.same, m.related], [['nets', 'fold', 'patfold'], []], 'an exercise that is the same kind for one tick is never "related"');
  m = O.match(['analogies']);
  t.eq([m.same, m.related], [[], []], 'word analogies: nothing trains them');
  t.ok(m.untrained.length === 1 && /Spatial Check’s word task/.test(m.untrained[0].text), 'and the answer says where the format appears');
  m = O.match(['matrices']);
  t.eq(m.related, ['rotate', 'spin', 'hidden'], 'figure matrices: related only');
  m = O.match(['dat']);
  t.eq(m.same, ['patviews', 'angles', 'patfold', 'cubes'], 'the PAT: the DAT-style exercises that exist');
  t.eq(m.related, ['fold', 'views', 'nets'], 'and Fold, Views, Nets related');
  m = O.match(['unsure']);
  t.ok(['fold', 'hidden', 'views', 'nets', 'span'].every((id) => m.same.includes(id)), 'not sure: every near format');
  t.eq(O.match(['bogus', null]).same, [], 'unknown kinds are ignored');
  t.eq(O.match('folding').same, [], 'a non-list is no ticks');
}

function testSettings(t) {
  t.section('overlap settings');
  const { PX } = env(t);
  const O = PX.ui.overlap, store = PX.core.store, rec = store.state;
  t.eq(O.registered, { patFocus: true, testPause: true, hygiene: true }, 'patFocus, testPause and the hygiene field are registered');
  t.eq([rec.settings.patFocus, rec.settings.testPause, rec.hygiene], [false, null, { tests: [], focus: [] }], 'defaults: focus off, no pause, empty log');
  t.eq(O.setFocus(rec, true, T0), true, 'focus on');
  O.setFocus(rec, true, T0 + 1000);
  O.setFocus(rec, false, T0 + 2000);
  t.eq(rec.hygiene.focus, [[T0 / 1000, 1], [T0 / 1000 + 2, 0]], 'the history logs changes only, in seconds');

  const today = O.today(T0), later = PX.util.addDays(today, 7), past = PX.util.addDays(today, -1);
  t.eq(O.pause(rec, ['folding'], past, T0), null, 'a day in the past is refused');
  t.eq(O.pause(rec, ['analogies'], later, T0), null, 'nothing to leave out: refused');
  t.eq(rec.settings.testPause, null, 'and nothing was set');
  const p = O.pause(rec, ['folding', 'counting', 'bogus'], later, T0);
  t.eq(p, { ids: ['fold', 'patfold', 'views', 'cubes'], until: later, what: ['folding', 'counting'] }, 'pause: the same-kind exercises until the day');
  t.eq(rec.settings.testPause, p, 'in settings.testPause (what js/engine/schedule.js reads)');
  t.eq(O.pauseState(rec, T0), { on: true, ids: p.ids, until: later, what: p.what, ended: false }, 'on before and on the day');
  t.ok(O.pauseState(rec, Date.parse(later + 'T23:00:00')).on, 'still on late on the day of the test');
  t.eq(O.pauseState(rec, Date.parse(PX.util.addDays(later, 1) + 'T00:30:00')).ended, true, 'ended the day after');
  t.eq(O.pause(rec, ['folding'], today, T0).until, today, 'today is allowed');
  O.clearPause(rec);
  t.eq([rec.settings.testPause, O.pauseState(rec, T0).on], [null, false], 'clearPause');

  const n1 = O.noteTest(rec, { date: later, kinds: ['folding', 'BAD'], paused: ['fold', 'Not An Id'] }, T0);
  t.eq(n1, { at: T0, date: later, kinds: ['folding'], paused: ['fold'] }, 'noteTest keeps clean values');
  O.noteTest(rec, { date: 'soon', kinds: [] }, T0 + 5);
  t.eq(rec.hygiene.tests[1].date, null, 'a bad date is kept as unknown');
  t.ok(O.removeTest(rec, T0 + 5) && rec.hygiene.tests.length === 1, 'removeTest');
  t.ok(!O.removeTest(rec, 42), 'removing what is not there');

  const fixP = O.fix.pause;
  t.eq([fixP(null), fixP('x'), fixP({ ids: ['fold'], until: 'tomorrow' })], [null, undefined, null], 'the setting repair: null, junk, a bad day');
  t.eq(fixP({ ids: ['fold', 'fold', 7, 'X'], until: '2026-12-01', what: ['folding'], extra: 1 }), { ids: ['fold'], until: '2026-12-01', what: ['folding'] }, 'and keeps what is valid');
  const fixH = O.fix.hygiene;
  t.eq(fixH([]), undefined, 'hygiene: not an object → default');
  t.eq(fixH({ tests: [{ at: 1, date: '2026-01-01', kinds: ['folding'] }, { at: -1 }, 'x'], focus: [[5.7, 1], [1, 2], 'x'] }),
    { tests: [{ at: 1, date: '2026-01-01', kinds: ['folding'], paused: [] }], focus: [[5, 1]] }, 'hygiene repair');
}

function testPersist(t) {
  t.section('overlap persistence');
  const storage = new SharedStorage();
  const a = env(t, storage);
  const O = a.PX.ui.overlap, store = a.PX.core.store, rec = store.state;
  const later = a.PX.util.addDays(O.today(T0), 3);
  O.setFocus(rec, true, T0);
  O.pause(rec, ['hidden'], later, T0);
  O.noteTest(rec, { date: later, kinds: ['hidden'], paused: ['hidden'] }, T0);
  store.save();
  a.clock.tick(6000);
  t.ok(storage.writes > 0, 'saved');
  const b = env(t, storage);
  const r2 = b.PX.core.store.state;
  t.eq([r2.settings.patFocus, r2.settings.testPause, clone(r2.hygiene)], [true, { ids: ['hidden'], until: later, what: ['hidden'] }, clone(rec.hygiene)], 'a reload keeps focus, pause and the noted test');
  const raw = JSON.parse(storage.get(b.PX.core.store.KEY));
  raw.settings.testPause = { ids: 'fold', until: 12 };
  raw.hygiene = 'broken';
  storage.set(null, b.PX.core.store.KEY, JSON.stringify(raw));
  const c = env(t, storage);
  const r3 = c.PX.core.store.state;
  t.eq([r3.settings.testPause, r3.hygiene], [null, { tests: [], focus: [] }], 'broken values load as safe defaults');
}

// The texts stay inside the honesty rules (CLAUDE.md rules 2, 10): no IQ, no promises, no scores.
function testWording(t) {
  t.section('overlap wording');
  const { PX } = env(t);
  const O = PX.ui.overlap;
  const texts = Object.values(O.NOTES).concat(PAT.map((id) => O.noteFor(id).text), O.KINDS.map((k) => k.label + ' ' + (k.untrained || '')));
  for (const s of texts) {
    t.ok(!/\bIQ\b|percentile|guarantee|boost|brain age|smarter|predicted|official/i.test(s), 'no forbidden claim in: ' + s.slice(0, 50));
  }
  t.ok(texts.every((s) => !/DAT(?!®| scores| score)/.test(s.replace('Dental Admission Test', ''))), 'the DAT is named only descriptively');
}
