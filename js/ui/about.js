/* PX.ui.screens.about: About (CLAUDE.md rules 1, 2, 3, 8, 10; PLAN §2, §9; v1.1 PLAN M5, M6).
   The Chimera community and its Discord (link, visible address, Copy); what training can and
   cannot do, in the words of research/A-evidence.md §4.3; Track as attention practice; test
   hygiene (the formats published tests share, the size of practice effects, what to do when a
   result matters, the "Taking a test soon?" helper, the ADA line: docs/research/v1.1/R4 §6.3,
   R3 §6); where the data lives; credits, licences and the references behind the claims. */
(function (PX) {
  'use strict';

  var ui = PX.ui;
  var h = ui.h;

  var REFS = [
    { text: 'Uttal, D. H., Meadow, N. G., Tipton, E., Hand, L. L., Alden, A. R., Warren, C., & Newcombe, N. S. (2013). The malleability of spatial skills: A meta-analysis of training studies. Psychological Bulletin, 139(2), 352–402.', doi: '10.1037/a0028446' },
    { text: 'Hawes, Z. C. K., Gilligan-Lee, K. A., & Mix, K. S. (2022). Effects of spatial training on mathematics performance: A meta-analysis. Developmental Psychology, 58(1), 112–137.', doi: '10.1037/dev0001281' },
    { text: 'Scharfen, J., Peters, J. M., & Holling, H. (2018). Retest effects in cognitive ability tests: A meta-analysis. Intelligence, 67, 44–66.', doi: '10.1016/j.intell.2018.01.003' },
    { text: 'Schneider, B., Becker, N., Krieger, F., Spinath, F. M., & Sparfeldt, J. R. (2020). Teaching the underlying rules of figural matrices in a short video increases test scores. Intelligence, 82, 101473.', doi: '10.1016/j.intell.2020.101473' },
    { text: 'Vater, C., Gray, R., & Holcombe, A. O. (2021). Psychonomic Bulletin & Review (a critical systematic review of a commercial 3D multiple-object tracking trainer).', doi: '10.3758/s13423-021-01892-2' },
  ];

  function ext(href, text) {
    return h('a', { href: href, target: '_blank', rel: 'noopener' }, text);
  }

  function section(title, kids, attrs) {
    return h('section.px-about-section', attrs || null, h('h2', title), kids);
  }

  function shortOf(id) { var d = PX.ex.get(id); return d ? d.short || d.name : null; }
  function andList(list) { return list.length < 2 ? list.join('') : list.slice(0, -1).join(', ') + ' and ' + list[list.length - 1]; }

  // Test hygiene (docs/research/v1.1/R4-test-overlap.md §6.3 a; R3 §6): the shared formats, the size
  // of practice effects, what to do when a result matters. Names come from the registry, so the
  // text lists only exercises this build has.
  function hygiene() {
    var O = PX.ui.overlap;
    var shared = [['paper folding', 'fold'], ['hidden shapes', 'hidden'], ['counting cubes', 'views'], ['cube nets', 'nets'], ['block tapping', 'span']]
      .filter(function (x) { return shortOf(x[1]); })
      .map(function (x) { return x[0] + ' (' + shortOf(x[1]) + ')'; });
    var pat = O ? O.patIds().map(shortOf).filter(Boolean) : [];
    var helper = ui.button('Taking a test soon?', { kind: 'secondary', small: true, go: 'settings?section=testsoon' });
    helper.setAttribute('data-about', 'testsoon');
    return [
      h('p', 'Every item is generated by Parallax and checked by a solver, so no exercise copies a published test. There are no clones of Wechsler Block Design or Visual Puzzles.'),
      h('p', 'Some exercises use the same kinds of puzzles as parts of published tests: ' + andList(shared) + '.' +
        (pat.length ? ' The DAT-style formats (' + andList(pat) + ') follow the Perceptual Ability Test of the Dental Admission Test on purpose.' : '')),
      h('p', 'Practising a kind of puzzle raises scores on tests that use it. Taking a test a second time adds about a third of a standard deviation on average, and being taught a puzzle type’s rules has added about one standard deviation in studies. These gains stay mostly with that kind of puzzle (Scharfen and colleagues, 2018; Schneider and colleagues, 2020).'),
      h('p', 'So if a test result matters to you, take the test before you practise its kind of puzzle here, or say how much you have practised. Analogy tests (“A is to B as C is to …”) are not trained here; the Spatial Check’s word task uses that format for a few minutes per check, without feedback.'),
      h('div.px-about-helper', h('p', 'Settings can list the exercises that match your test and leave them out of Train until the day of the test.'), helper),
      h('p', 'Parallax is a practice tool. It is not a test of intelligence and not a diagnostic tool.'),
      pat.length && O ? h('p.px-meta.px-overlap-legal', O.ADA) : null,
    ];
  }

  function render(host) {
    var C = PX.ui.chimera;
    var copy = C.linkCopy({ label: 'Chimera Discord address' });

    host.appendChild(h('div.px-about',
      h('div.px-screen-head',
        h('h1', 'About Parallax'),
        h('p.px-lead', 'Parallax is a free, open-source trainer for visuospatial ability: picturing objects as they turn, fold, are cut, or are seen from somewhere else. It works offline in your browser.'),
        PX.ui.figures.plate({ className: 'px-about-plate', label: 'Drawing of one block figure seen from two viewpoints, turned 90 degrees about its vertical axis' })),

      section('Built by the Chimera community', [
        h('div.px-panel.px-about-chimera',
          h('p', 'Parallax was built by the Chimera community on Discord. Come say hi, share your results, and suggest exercises you would like to train.'),
          C.joinLink({ onClick: function () { C.nudgeIfBlocked(copy); } }),
          copy),
      ], { 'data-section': 'chimera' }),

      section('What training can and cannot do', [
        h('p', 'Spatial practice reliably improves spatial test performance, even on tests you have not practised, for weeks. Benefits beyond that are small or unproven, so Parallax measures your transfer instead of promising it.'),
        h('ul',
          h('li', 'Practising spatial tasks improves those tasks and, often, similar spatial tests you never practised, for at least several weeks (Uttal and colleagues, 2013: 206 studies).'),
          h('li', 'Gains in school mathematics are small and were shown mainly in children and teenagers (Hawes and colleagues, 2022). Effects on grades, work or sport are not established.'),
          h('li', 'There is no good evidence that spatial training raises IQ or makes anyone smarter. Parallax does not claim it, and shows no IQ, percentile, index or “brain age”.'),
          h('li', 'Part of any improvement on a repeated test is familiarity with the test itself (Scharfen and colleagues, 2018). The Spatial Check therefore uses tasks you never train, starts with two baselines, and compares your change with a non-spatial control task. When a change cannot be told apart from familiarity or from the control task’s change, it says “unclear yet”, which is not the same as no progress.'),
          h('li', 'Levels are estimates with a likely range, not scores. The range narrows as you practise.')),
      ], { 'data-section': 'claims' }),

      section('Track is attention practice', [
        h('p', 'Track (EX-01, 3D multiple-object tracking) trains following several moving objects at once. It is related to attention and working memory rather than to visuospatial ability, and evidence that its gains carry over to other tasks is weak (Vater and colleagues, 2021). Parallax labels it attention practice, not visuospatial training.'),
      ], { 'data-section': 'track' }),

      section('Test hygiene', hygiene(), { 'data-section': 'hygiene' }),

      section('Your data', [
        h('p', 'Everything you do stays in this browser on this device. Nothing is sent anywhere: there are no accounts, no analytics and no ads. Back up in Settings to keep a copy or move to another device.'),
        h('p', ui.button('Open Settings', { kind: 'secondary', small: true, go: 'settings' })),
      ], { 'data-section': 'data' }),

      section('Credits and licences', [
        h('dl.px-credits',
          h('div', h('dt', 'Parallax'), h('dd', 'Built by the Chimera community. Version ', h('span.px-num', PX.version), '.')),
          h('div', h('dt', 'Code'), h('dd', 'MIT licence.')),
          h('div', h('dt', 'Guide text'), h('dd', 'Creative Commons Attribution-ShareAlike 4.0 (CC BY-SA 4.0).')),
          h('div', h('dt', 'three.js'), h('dd', '3D rendering. MIT licence, © 2010–2026 three.js authors.')),
          h('div', h('dt', 'IBM Plex Sans and Mono'), h('dd', 'Typefaces by IBM. SIL Open Font License 1.1.'))),
      ], { 'data-section': 'credits' }),

      section('References', [
        h('ul.px-refs', REFS.map(function (r) {
          return h('li', r.text + ' ', ext('https://doi.org/' + r.doi, 'doi.org/' + r.doi));
        })),
        h('p.px-meta', 'The guide lists the full research notes behind every exercise.'),
      ], { 'data-section': 'refs' })));
  }

  PX.ui.screens = PX.ui.screens || {};
  PX.ui.screens.about = { title: 'About', render: render };
})(window.PX);
