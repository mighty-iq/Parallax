/* PX.ui.screens.about: About (CLAUDE.md rules 1, 2, 3, 8, 10; PLAN §2, §9; v1.1 PLAN M5, M6; v1.2 PLAN
   milestone 10, the voice: what Parallax trains, bets on and measures, one accurate limit where a claim needs
   it). The Chimera community and its Discord (link, visible address, Copy); what spatial practice does, in the
   words of research/A-evidence.md §4.3, and how the Spatial Check measures it (ENGINE.md §21); the bets come
   right after it from js/ui/bets.js (about:sections, after 'claims'); Track as attention practice; test
   hygiene (the formats published tests share, the size of practice effects, what to do when a
   result matters, the "Taking a test soon?" helper, the ADA line: docs/research/v1.1/R4 §6.3,
   R3 §6); where the data lives; credits, licences and the references behind the claims. */
(function (PX) {
  'use strict';

  var ui = PX.ui;
  var h = ui.h;

  var REFS = [
    { text: 'Uttal, D. H., Meadow, N. G., Tipton, E., Hand, L. L., Alden, A. R., Warren, C., & Newcombe, N. S. (2013). The malleability of spatial skills: A meta-analysis of training studies. Psychological Bulletin, 139(2), 352–402.', doi: '10.1037/a0028446' },
    { text: 'Hawes, Z. C. K., Gilligan-Lee, K. A., & Mix, K. S. (2022). Effects of spatial training on mathematics performance: A meta-analysis. Developmental Psychology, 58(1), 112–137.', doi: '10.1037/dev0001281' },
    { text: 'Scharfen, J., Peters, J. M., & Holling, H. (2018). Retest effects in cognitive ability tests: A meta-analysis. Intelligence, 67, 44–66.', doi: '10.1016/j.intell.2018.01.003' },
    { text: 'Schneider, B., Becker, N., Krieger, F., Spinath, F. M., & Sparfeldt, J. R. (2020). Teaching the underlying rules of figural matrices in a short video increases test scores. Intelligence, 82, 101473.', doi: '10.1016/j.intell.2020.101473' },
    { text: 'te Nijenhuis, J., van Vianen, A. E. M., & van der Flier, H. (2007). Score gains on g-loaded tests: No g. Intelligence, 35.', doi: '10.1016/j.intell.2006.07.006' },
    { text: 'Vater, C., Gray, R., & Holcombe, A. O. (2021). Psychonomic Bulletin & Review (a critical systematic review of a commercial 3D multiple-object tracking trainer).', doi: '10.3758/s13423-021-01892-2' },
  ];

  function ext(href, text) {
    return h('a', { href: href, target: '_blank', rel: 'noopener' }, text);
  }

  function section(title, kids, attrs) {
    return h('section.px-about-section', attrs || null, h('h2', title), kids);
  }

  function shortOf(id) { var d = PX.ex.get(id); return d ? d.short || d.name : null; }
  function andList(list) { return list.length < 2 ? list.join('') : list.slice(0, -1).join(', ') + ' and ' + list[list.length - 1]; }

  // Test hygiene (docs/research/v1.1/R4-test-overlap.md §6.3 a; R3 §6): the shared formats, the size
  // of practice effects, what to do when a result matters. Names come from the registry, so the
  // text lists only exercises this build has.
  function hygiene() {
    var O = PX.ui.overlap;
    // one source of truth with the "Also in tests" notes and the helper (overlap.js NEAR)
    var shared = (O ? O.shared() : []).map(function (x) { return x.format + ' (' + x.name + ')'; });
    var pat = O ? O.patIds().map(shortOf).filter(Boolean) : [];
    var helper = ui.button('Taking a test soon?', { kind: 'secondary', small: true, go: 'settings?section=testsoon' });
    helper.setAttribute('data-about', 'testsoon');
    return [
      h('p', 'Every item is generated by Parallax and checked by a solver, so no exercise copies a published test, and there are no clones of Wechsler Block Design or Visual Puzzles. Parallax is a practice tool, not a test of intelligence or a diagnostic tool.'),
      h('p', 'Some exercises use the same kinds of puzzles as parts of published tests: ' + andList(shared) + '.' +
        (pat.length ? ' The DAT-style formats (' + andList(pat) + ') follow the Perceptual Ability Test of the Dental Admission Test on purpose.' : '')),
      h('p', 'Practising a kind of puzzle raises scores on tests that use it. Taking a test a second time adds about a third of a standard deviation on average (Scharfen and colleagues, 2018), and being taught a puzzle type’s rules has added about one standard deviation in studies (Schneider and colleagues, 2020). These gains stay mostly with that kind of puzzle (te Nijenhuis and colleagues, 2007).'),
      h('p', 'So if a test result matters to you, take the test before you practise its kind of puzzle here, or say how much you have practised. That keeps your result, and the community’s data, clean.'),
      h('p', { 'data-about': 'analogy' }, O && O.ANALOGY ? O.ANALOGY : 'Analogy tests (“A is to B as C is to …”) are not trained here; the Spatial Check’s word task uses that format for a few minutes per check, without feedback.'),
      h('div.px-about-helper', h('p', 'Settings can list the exercises that match your test and leave them out of Train until the day of the test.'), helper),
      pat.length && O ? h('p.px-meta.px-overlap-legal', O.ADA) : null,
    ];
  }

  function render(host) {
    var C = PX.ui.chimera;
    var copy = C.linkCopy({ label: 'Chimera Discord address' });

    var box = h('div.px-about',
      h('div.px-screen-head',
        h('h1', 'About Parallax'),
        h('p.px-lead', 'Parallax is a free, open-source trainer for visuospatial ability: picturing objects as they turn, fold, are cut, or are seen from somewhere else. Every exercise names the mechanism of transfer it bets on, and the Spatial Check follows your own change on tasks you never train. Test the bets with us. It works offline in your browser.'),
        PX.ui.figures.plate({ className: 'px-about-plate', label: 'Drawing of one block figure seen from two viewpoints, turned 90 degrees about its vertical axis' })),

      section('Built by the Chimera community', [
        h('div.px-panel.px-about-chimera',
          h('p', 'Parallax was built by the Chimera community on Discord. Come say hi, share your results, and suggest exercises you would like to train.'),
          C.joinLink({ onClick: function () { C.nudgeIfBlocked(copy); } }),
          copy),
      ], { 'data-section': 'chimera' }),

      section('What practice does, and how Parallax measures it', [
        h('p', 'Spatial practice works on spatial tests: across 206 training studies it raised scores by about half a standard deviation, and spatial tests nobody had practised gained about as much, for at least several weeks (Uttal and colleagues, 2013). How far the gains reach beyond spatial tests is the open question: in school mathematics they were small and shown mainly in children and teenagers (Hawes and colleagues, 2022). Parallax is built to help answer it.'),
        h('ul',
          h('li', 'The Spatial Check measures you on tasks you never train: one near, three mid and two far, with a word task as a control. Two baselines set your starting point, short blocks at the start of some sessions keep the measure moving, and one model reads them all together.'),
          h('li', 'Retaking any task raises scores on its own (Scharfen and colleagues, 2018), so the model allows for familiarity and for ordinary day-to-day ups and downs. A meter shows how likely it is that your probe scores have risen beyond what familiarity predicts; at milestones it puts that into words. “Unclear yet” is not the same as no progress.'),
          h('li', 'Levels are estimates with a likely range that narrows as you practise. Everything compares you with yourself: Parallax shows no IQ, percentile, index or “brain age”, and promises no outcome.')),
      ], { 'data-section': 'claims' }),

      section('Track is attention practice', [
        h('p', 'Track (EX-01, 3D multiple-object tracking) trains following several moving objects at once, which draws on attention and working memory more than on visuospatial ability, so Parallax labels it attention practice. Its bet is attention control. Studies of tracking practice itself found large gains on the task and weak evidence of carry-over (Vater and colleagues, 2021); the pooled exports can test the bet.'),
      ], { 'data-section': 'track' }),

      section('Test hygiene', hygiene(), { 'data-section': 'hygiene' }),

      section('Your data', [
        h('p', 'Everything you do stays in this browser on this device. Nothing is sent anywhere: there are no accounts, no analytics and no ads. Back up in Settings to keep a copy or move to another device. To help test the bets, share the community export from the Lab: it carries no name unless you add your nickname, and no device details, screen sizes included, unless you tick them.'),
        h('p', ui.button('Open Settings', { kind: 'secondary', small: true, go: 'settings' })),
      ], { 'data-section': 'data' }),

      section('Credits and licences', [
        h('dl.px-credits',
          h('div', h('dt', 'Parallax'), h('dd', 'Built by the Chimera community on Discord. Version ', h('span.px-num', PX.version), '.')),
          h('div', h('dt', 'Code'), h('dd', 'MIT licence.')),
          h('div', h('dt', 'Guide and texts'), h('dd', 'The guide and its figures, the README, the CHANGELOG and the notes: Creative Commons Attribution-ShareAlike 4.0 (CC BY-SA 4.0).')),
          h('div', h('dt', 'three.js'), h('dd', '3D rendering. MIT licence, © 2010–2026 three.js authors.')),
          h('div', h('dt', 'IBM Plex Sans and Mono'), h('dd', 'Typefaces by IBM. SIL Open Font License 1.1.'))),
      ], { 'data-section': 'credits' }),

      section('References', [
        h('ul.px-refs', REFS.map(function (r) {
          return h('li', r.text + ' ', ext('https://doi.org/' + r.doi, 'doi.org/' + r.doi));
        })),
        h('p.px-meta', 'The guide lists the full research notes behind every exercise.'),
      ], { 'data-section': 'refs' }));
    // v1.2 wave 2 (CONTRACT-v1.2 R): sections other modules add, after the section they name
    if (PX.ui.hooks && typeof PX.ui.hooks.screen === 'function') PX.ui.hooks.screen('about:sections', box, { rec: PX.core.store.state });
    host.appendChild(box);
  }

  PX.ui.screens = PX.ui.screens || {};
  PX.ui.screens.about = { title: 'About', render: render };
})(window.PX);
